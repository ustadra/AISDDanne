#!/usr/bin/env node
// no-ai-attribution — commits y PR salen con la autoría del desarrollador, sin marcas de ningún agente de IA.
// PreToolUse hook sobre Bash | PowerShell. Exit 2 → bloquea y dice qué quitar.
//
// Vale para cualquier agente, no solo para Claude: el repo es multi-agente (ver AGENTS.md) y
// Codex, Gemini, Cursor, Copilot, Aider, Devin… firman cada uno a su manera — con una línea de
// coautor, con un pie «Generated with…», con un trailer propio o poniéndose de autor del commit.
// Ninguna de esas firmas debe llegar a GitHub: quien responde del cambio es quien lo sube.
//
// Qué mira:
//   · `git commit`         → el mensaje: -m inline, heredoc y ficheros de -F/--file (relativos al
//                            directorio de `-C` o del `cd` previo); `--trailer k: v` y `--trailer k=v`;
//                            la identidad de `--author` y de `-c user.name=…`/`-c user.email=…`.
//   · `gh pr create|edit|comment|review|merge|close|reopen` y `gh issue create|edit|comment|close|reopen` →
//                            título o asunto (--subject de merge), cuerpo y comentario de cierre
//                            (-c/--comment): inline y --body-file / -F. Las issues las abre `/mejora`, en el repo del proyecto o en el del kit.
//   · `git push`           → autor, committer y mensaje de los commits de las refs que se empujan
//                            (las del refspec, todos los posicionales si va `--repo`, o la rama actual)
//                            que aún no están en ningún remoto. Si no se pueden leer a tiempo, bloquea.
// No mira el diff: un fichero que hable de estas marcas (como este) no es una firma.
//
// Qué cuenta como firma:
//   · En trailers (Co-authored-by, Generated-by…) y pies («Generated with…», «Created with…»,
//     «Made with…»): el nombre de un agente como palabra completa (`devinci.fr` no es Devin) o su dominio.
//   · Pies, trailers y 🤖 solo cuentan en su sitio de firma: a principio de línea o abriendo el valor
//     de un -m, --title, --body o --trailer. Dentro de una frase o entre comillas internas
//     (`-m "feat: detecta el pie 'Generated with…'"`) son texto y pasan.
//   · Autor o committer del push: correos de bot exactos y nombres de herramienta, nunca un nombre de
//     pila suelto (Claude, Jules, Devin, Cline o Grok pueden ser personas del equipo).
//
// Para cubrir un agente nuevo: añade su nombre a AGENTES y, si firma con un dominio, un correo o un
// nombre de autor propios, a DOMINIOS, CORREOS_BOT o NOMBRES_BOT. Nada más.
//
// Es la red de seguridad de la regla de autoría de AGENTS.md: `attribution` vacío en
// .claude/settings.json evita que Claude Code firme; este hook cubre al resto de agentes y a quien
// escriba la firma a mano.

